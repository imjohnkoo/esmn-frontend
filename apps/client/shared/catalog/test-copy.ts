/**
 * 테스트 전용 — 카피 금지어(catalog spec 불변식 5 · F-7 · 메모리 카피 규칙). 상세 문안 · 메타 문구 테스트가 같은 목록을 쓴다.
 */
export const BANNED_COPY: [RegExp, string][] = [
  [
    /(?<!사업)자정|(밤|오전) ?(12|열두) ?(시|:00)|(?<!\d)12(:00)? ?a\.?m(?![a-z])|(?<!\d)0:00|(날짜|일자|하루|날)(가|이)? ?(바뀌|넘어가)|(현지|한국|달력) ?(날짜|날) ?기준|(?<![\d:])(0|00|24) ?시(?!간)|(?<!\d)(00|24):00|정각|선택(한|하신)? 시각/i,
    '사용일수는 첫 연결부터 24h rolling',
  ],
  [/iPhone/i, '«아이폰»'],
  [/1~90일/, '판매는 1~30 · 60 · 90'],
  [/즉시할인|정가|할인율/, '최종가만(D-2)'],
  [
    /재개통|다시 개통|나라마다 (다시 )?설치|직접 (골라|선택)|수동으로|설정에서 [^.]{0,12}통신사|별도 (설정|조작)|(네트워크|통신사)를? (다시|새로) (골라|선택)|APN/,
    '여러 나라 = 자동 전환',
  ],
  [/최고|최저가 보장|유일|1위/, '근거 없는 최상급'],
  [/500\s?kbps|128\s?kbps/i, '소진 후 속도는 512kbps'],
  [/이어 쓰기|충전/, 'top-up 없음'],
]

/** 글자에서 처음 걸리는 금지어들 — 없으면 [] */
export function bannedIn(text: string): string[] {
  return BANNED_COPY.flatMap(([re, why]) => {
    const m = text.match(re)?.[0]
    return m ? [`«${m}» — ${why}`] : []
  })
}
