import { describe, expect, it } from 'vitest'
import { bannedIn } from './test-copy'

describe('금지어 목록(테스트 도우미) — 대조군', () => {
  it.each([
    '현지 자정에 하루가 줄어요',
    '밤 12시 기준',
    '밤 열두 시에 바뀌어요',
    '오전 12시',
    '12:00 AM',
    '0:00 에 갱신',
    '00시 기준',
    '24:00 까지',
    '날짜가 바뀌면 하루가 줄어요',
    '하루가 바뀌는 시점',
    '밤 12:00 가 지나면',
    '오전 12:00',
    '하루가 바뀌면',
    '날이 바뀌면',
    '12am',
    '12:00 am',
    '12 A.M.',
    '현지 날짜 기준으로',
    'iPhone 에서',
    '1~90일 중에서',
    '즉시할인 적용',
    '나라마다 다시 설치',
    '설정에서 통신사를 골라',
    'APN 을 넣어',
    '최저가 보장',
    '500kbps',
    '충전해서 이어 쓰기',
  ])('잡는다 — %s', (t) => {
    expect(bannedIn(t).length).toBeGreaterThan(0)
  })

  it.each([
    '사업자정보',
    '처음 연결된 때부터 24시간 단위',
    '오후 3시 · 2일째',
    '아이폰 · 갤럭시',
    '512kbps 로 계속',
    '1~30일 · 60·90일',
    '하루 약 1,200원',
    '매일 12GB',
    '결제한 날짜',
  ])('잡지 않는다 — %s', (t) => {
    expect(bannedIn(t)).toEqual([])
  })
})
